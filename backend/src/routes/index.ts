import marketingModule from '../modules/marketing';
import storeModule from '../modules/store';
import financeModule from '../modules/finance';
import { crudRouter } from '../lib/crud';

export function createRoutes() {
  const router = Router();

  // Provider webhooks (signature-verified, no user auth).
  router.use('/webhooks', webhookRoutes);

  // Workflow endpoints (multi-step business actions). Mounted before the generic CRUD routes so
  // e.g. POST /payments runs the payment workflow; other methods fall through to generic CRUD.
  router.use(meRoutes);
  router.use(teamRoutes);
  router.use(crmModule);
  router.use(billingModule);
  router.use(filesModule);
  router.use(creativeModule);
  router.use(marketingModule);
  router.use(storeModule);
  router.use(financeModule);

  // Generic CRUD for models added with the five modules (access rules in src/access/policy.ts).
  router.use('/pipelines', crudRouter({ model: 'pipeline', searchableFields: ['name'] }));
  router.use('/pipeline-stages', crudRouter({ model: 'pipelineStage', orderBy: { sortOrder: 'asc' }, searchableFields: ['name'] }));
  router.use('/deals', crudRouter({ model: 'deal', searchableFields: ['title', 'notes'] }));
  router.use('/deal-stage-changes', crudRouter({ model: 'dealStageChange' }));
  router.use('/crm-tasks', crudRouter({ model: 'crmTask', orderBy: { dueAt: 'asc' }, searchableFields: ['title', 'description'] }));
  router.use('/client-subscription-events', crudRouter({ model: 'clientSubscriptionEvent' }));
  router.use('/project-members', crudRouter({ model: 'projectMember' }));
  router.use('/project-comments', crudRouter({ model: 'projectComment', orderBy: { createdAt: 'asc' }, searchableFields: ['body'] }));
  router.use('/automation-executions', crudRouter({ model: 'automationExecution' }));
  router.use('/financial-categories', crudRouter({ model: 'financialCategory', orderBy: { name: 'asc' }, searchableFields: ['name'] }));
  router.use('/report-exports', crudRouter({ model: 'reportExport' }));

  router.use('/admin/dashboard', adminDashboardRoutes);
  router.use('/auth', authRoutes);
  router.use('/users', usersRoutes);
  router.use('/businesses', businessesRoutes);
  router.use('/business-memberships', businessMembershipsRoutes);
  router.use('/plans', plansRoutes);
  router.use('/subscriptions', subscriptionsRoutes);
  router.use('/subscription-billing-records', subscriptionBillingRecordsRoutes);
  router.use('/crm-customers', crmCustomersRoutes);
  router.use('/leads', leadsRoutes);
  router.use('/creative-requests', creativeRequestsRoutes);
  router.use('/creative-projects', creativeProjectsRoutes);
  router.use('/creative-tasks', creativeTasksRoutes);
  router.use('/creative-reviews', creativeReviewsRoutes);
  router.use('/marketing-contacts', marketingContactsRoutes);
  router.use('/campaigns', campaignsRoutes);
  router.use('/campaign-recipients', campaignRecipientsRoutes);
  router.use('/stores', storesRoutes);
  router.use('/store-domains', storeDomainsRoutes);
  router.use('/product-categories', productCategoriesRoutes);
  router.use('/products', productsRoutes);
  router.use('/product-variants', productVariantsRoutes);
  router.use('/inventory-movements', inventoryMovementsRoutes);
  router.use('/store-customers', storeCustomersRoutes);
  router.use('/store-orders', storeOrdersRoutes);
  router.use('/store-order-items', storeOrderItemsRoutes);
  router.use('/store-order-status-events', storeOrderStatusEventsRoutes);
  router.use('/finance-transactions', financeTransactionsRoutes);
  router.use('/invoices', invoicesRoutes);
  router.use('/invoice-items', invoiceItemsRoutes);
  router.use('/payments', paymentsRoutes);
  router.use('/notifications', notificationsRoutes);
  router.use('/file-assets', fileAssetsRoutes);
  router.use('/integration-connections', integrationConnectionsRoutes);
  router.use('/webhook-events', webhookEventsRoutes);
  router.use('/audit-logs', auditLogsRoutes);
  router.use('/client-onboardings', clientOnboardingsRoutes);
  router.use('/client-onboarding-tasks', clientOnboardingTasksRoutes);
  router.use('/service-packages', servicePackagesRoutes);
  router.use('/client-subscriptions', clientSubscriptionsRoutes);
  router.use('/client-communications', clientCommunicationsRoutes);
  router.use('/creative-deliverables', creativeDeliverablesRoutes);
  router.use('/whatsapp-accounts', whatsappAccountsRoutes);
  router.use('/contact-segments', contactSegmentsRoutes);
  router.use('/contact-segment-members', contactSegmentMembersRoutes);
  router.use('/contact-consent-events', contactConsentEventsRoutes);
  router.use('/message-templates', messageTemplatesRoutes);
  router.use('/automation-rules', automationRulesRoutes);
  router.use('/auto-replies', autoRepliesRoutes);
  router.use('/chatbot-flows', chatbotFlowsRoutes);
  router.use('/message-logs', messageLogsRoutes);
  router.use('/supplier-profiles', supplierProfilesRoutes);
  router.use('/supplier-documents', supplierDocumentsRoutes);
  router.use('/supplier-products', supplierProductsRoutes);
  router.use('/product-import-jobs', productImportJobsRoutes);
  router.use('/reseller-profiles', resellerProfilesRoutes);
  router.use('/reseller-products', resellerProductsRoutes);
  router.use('/product-sync-events', productSyncEventsRoutes);
  router.use('/promotion-links', promotionLinksRoutes);
  router.use('/referral-clicks', referralClicksRoutes);
  router.use('/order-fulfillments', orderFulfillmentsRoutes);
  router.use('/reseller-commissions', resellerCommissionsRoutes);
  router.use('/contact-messages', contactMessagesRoutes);

  router.get('/health', (_req, res) => {
    res.json({ status: 'ok', timestamp: new Date().toISOString() });
  });

  return router;
}

export default createRoutes;
